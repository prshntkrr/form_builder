def seed_default_packs():
    from app.core.database import transaction

    with transaction() as cur:
        cur.execute("SELECT 1 FROM language_pack WHERE language = 'en-US'")
        if cur.fetchone():
            return

        logger.info("Seeding default language packs (en-US, es-MX, hi-IN)")
        for lang, label, pack in [
            ("en-US", "English", EN_US),
            ("es-MX", "Español", ES_MX),
            ("hi-IN", "हिंदी", HI_IN),
        ]:
            cur.execute(
                "INSERT INTO language_pack (language, label, pack)"
                " VALUES (%s, %s, %s) ON CONFLICT DO NOTHING",
                (lang, label, json.dumps(pack)),
            )


